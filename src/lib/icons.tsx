interface IconProps {
  name: string;
  size?: number;
  stroke?: number;
  className?: string;
}

export function Icon({ name, size = 26, stroke = 1.5, className }: IconProps) {
  const Glyph = ICONS[name];
  if (!Glyph) throw new Error(`Icon "${name}" is not in src/lib/icons.tsx. Add it to the map.`);
  return <Glyph size={size} stroke={stroke} className={cn('icon shrink-0', className)} aria-hidden="true" focusable="false" />;
}
